"""Offline design-contract checks; no PostgreSQL credentials or connections."""

from pathlib import Path

from src.database.schema import SCHEMA_SQL, MIGRATION_1_TO_2, MIGRATION_2_TO_3
from src.reviewer_accounts import initialize_accounts


ROOT = Path(__file__).resolve().parents[1]
SCHEMA = (ROOT / "config/postgres/001_schema.sql").read_text(encoding="utf-8")
PERMISSIONS = (ROOT / "config/postgres/002_permissions.sql").read_text(
    encoding="utf-8"
)
TABLES = (
    "opportunities", "collection_runs", "notification_history",
    "opportunity_reviews", "notification_jobs",
)
PRIVATE = ("reviewer_accounts", "reviewer_account_audit")


def test_all_opportunity_tables_mapped():
    for table in TABLES:
        assert f"CREATE TABLE phtech.{table} (" in SCHEMA


def test_reviewer_tables_restricted_to_private_namespace():
    for table in PRIVATE:
        assert f"CREATE TABLE phtech_private.{table} (" in SCHEMA
        assert f"CREATE TABLE phtech.{table} (" not in SCHEMA


def test_legacy_ids_timestamps_and_job_states_remain_representable():
    assert SCHEMA.count("GENERATED BY DEFAULT AS IDENTITY") == 6
    assert "account_id TEXT PRIMARY KEY" in SCHEMA
    for status in ("pending", "sending", "sent", "failed", "uncertain"):
        assert f"'{status}'" in SCHEMA
    for field in ("reviewed_at TEXT NOT NULL", "claimed_at TEXT",
                  "first_seen_at TEXT NOT NULL", "changed_at TEXT NOT NULL"):
        assert field in SCHEMA
    assert "CHECK (free_confirmed IN (0, 1))" in SCHEMA


def test_constraints_for_deduplication_and_history_retention():
    assert SCHEMA.count("UNIQUE (opportunity_id, channel, notification_type)") == 2
    assert "UNIQUE (source_id, url)" in SCHEMA
    assert "ON DELETE RESTRICT" in SCHEMA
    for trigger in ("protect_review_updates", "protect_review_deletes",
                    "protect_account_audit_updates",
                    "protect_account_audit_deletes"):
        assert f"CREATE TRIGGER {trigger}" in SCHEMA


def test_schema_has_no_credentials_or_live_migration_steps():
    low = SCHEMA.lower()
    for forbidden in ("password '", "dblink(", "copy ", "truncate ",
                      "drop table", "create extension", "insert into "):
        assert forbidden not in low
    assert "CREATE ROLE" not in SCHEMA


def test_no_login_roles_and_no_private_account_grants():
    assert PERMISSIONS.count("CREATE ROLE phtech_") == 3
    assert PERMISSIONS.count("NOLOGIN") >= 3
    assert "GRANT INSERT ON phtech.opportunity_reviews TO phtech_reviewer" in PERMISSIONS
    assert "GRANT UPDATE" in PERMISSIONS
    assert "GRANT DELETE" not in PERMISSIONS
    assert "GRANT CREATE" not in PERMISSIONS
    assert "GRANT INSERT ON phtech.notification_jobs" not in PERMISSIONS
    assert "GRANT UPDATE ON phtech.notification_jobs" not in PERMISSIONS
    assert "GRANT USAGE ON SCHEMA phtech_private" not in PERMISSIONS
    assert "GRANT ALL" not in PERMISSIONS
    assert "PASSWORD" not in PERMISSIONS
    assert "LOGIN " not in PERMISSIONS.replace("NOLOGIN ", "")


def test_postgres_schema_not_applied_implicitly():
    from src.database import schema
    assert schema.SCHEMA_VERSION == 3
    assert "CREATE TABLE IF NOT EXISTS opportunities" in schema.SCHEMA_SQL
    assert "CREATE TABLE opportunity_reviews" in schema.MIGRATION_1_TO_2
    assert "CREATE TABLE notification_jobs" in schema.MIGRATION_2_TO_3


def test_original_sqlite_account_bootstrap_remains_local(tmp_path):
    path = tmp_path / "existing_accounts.sqlite3"
    initialize_accounts(path)
    assert path.is_file()
    assert not (tmp_path / "phtech_staging").exists()
