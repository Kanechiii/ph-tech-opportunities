-- Phase 10 / Step 3: PostgreSQL schema *design*, initially run only on
-- a disposable Neon child branch. Never run on production or import real rows.
--
-- Deliberately preserve SQLite text timestamps, BIGINT IDs, and 0/1 flags
-- for lossless later reconciliation. A future migration must reset identity
-- sequences after importing explicit historical IDs.
BEGIN;

CREATE SCHEMA phtech;
CREATE SCHEMA phtech_private;

CREATE TABLE phtech.opportunities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id TEXT NOT NULL,
    url TEXT NOT NULL,
    title TEXT NOT NULL,
    category TEXT NOT NULL DEFAULT 'unclassified'
        CHECK (category IN (
            'unclassified', 'certification_voucher', 'tech_event', 'hackathon'
        )),
    classification_status TEXT NOT NULL DEFAULT 'unclassified'
        CHECK (classification_status IN ('unclassified', 'potential_match')),
    verification TEXT NOT NULL DEFAULT 'not_verified',
    free_status TEXT NOT NULL DEFAULT 'unknown',
    ph_eligibility TEXT NOT NULL DEFAULT 'unknown',
    deadline_status TEXT NOT NULL DEFAULT 'unknown',
    published_at TEXT,
    first_seen_at TEXT NOT NULL DEFAULT to_char(
        CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'
    ),
    last_seen_at TEXT NOT NULL DEFAULT to_char(
        CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'
    ),
    UNIQUE (source_id, url)
);
CREATE INDEX idx_opportunities_category ON phtech.opportunities (category);
CREATE INDEX idx_opportunities_verification ON phtech.opportunities (verification);

CREATE TABLE phtech.collection_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id TEXT NOT NULL,
    started_at TEXT NOT NULL DEFAULT to_char(
        CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'
    ),
    finished_at TEXT,
    status TEXT NOT NULL DEFAULT 'running'
        CHECK (status IN ('running', 'success', 'partial', 'failed')),
    items_found BIGINT NOT NULL DEFAULT 0 CHECK (items_found >= 0),
    error_type TEXT
);
CREATE INDEX idx_collection_runs_source ON phtech.collection_runs (source_id);

CREATE TABLE phtech.notification_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    opportunity_id BIGINT NOT NULL REFERENCES phtech.opportunities (id)
        ON DELETE RESTRICT,
    channel TEXT NOT NULL DEFAULT 'email' CHECK (channel = 'email'),
    notification_type TEXT NOT NULL DEFAULT 'new_opportunity',
    sent_at TEXT NOT NULL DEFAULT to_char(
        CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'
    ),
    UNIQUE (opportunity_id, channel, notification_type)
);

CREATE TABLE phtech.opportunity_reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    opportunity_id BIGINT NOT NULL REFERENCES phtech.opportunities (id)
        ON DELETE RESTRICT,
    decision TEXT NOT NULL CHECK (decision IN ('approved', 'rejected')),
    method TEXT NOT NULL DEFAULT 'manual' CHECK (method = 'manual'),
    reviewer_id TEXT NOT NULL CHECK (length(btrim(reviewer_id)) > 0),
    evidence_url TEXT NOT NULL CHECK (length(btrim(evidence_url)) > 0),
    free_confirmed SMALLINT NOT NULL DEFAULT 0 CHECK (free_confirmed IN (0, 1)),
    ph_confirmed SMALLINT NOT NULL DEFAULT 0 CHECK (ph_confirmed IN (0, 1)),
    open_confirmed SMALLINT NOT NULL DEFAULT 0 CHECK (open_confirmed IN (0, 1)),
    reviewed_at TEXT NOT NULL
);
CREATE INDEX idx_reviews_opportunity
    ON phtech.opportunity_reviews (opportunity_id, id DESC);

CREATE TABLE phtech.notification_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    opportunity_id BIGINT NOT NULL REFERENCES phtech.opportunities (id)
        ON DELETE RESTRICT,
    channel TEXT NOT NULL DEFAULT 'email' CHECK (channel = 'email'),
    notification_type TEXT NOT NULL DEFAULT 'new_opportunity',
    status TEXT NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'sending', 'sent', 'failed', 'uncertain')),
    attempt_count BIGINT NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    claim_token TEXT,
    claimed_at TEXT,
    created_at TEXT NOT NULL DEFAULT to_char(
        CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'
    ),
    updated_at TEXT NOT NULL DEFAULT to_char(
        CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'
    ),
    sent_at TEXT,
    last_error_type TEXT,
    UNIQUE (opportunity_id, channel, notification_type)
);
CREATE INDEX idx_notification_jobs_status
    ON phtech.notification_jobs (status, created_at);

-- Private account records are deliberately separated from public metadata.
-- Do not add foreign keys from legacy reviewer IDs to accounts: historical
-- pre-authentication reviews may not refer to any current account.
CREATE TABLE phtech_private.reviewer_accounts (
    account_id TEXT PRIMARY KEY,
    role TEXT NOT NULL
        CHECK (role IN ('administrator', 'reviewer', 'viewer')),
    password_hash TEXT NOT NULL,
    active SMALLINT NOT NULL DEFAULT 1 CHECK (active IN (0, 1)),
    created_at TEXT NOT NULL DEFAULT to_char(
        CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'
    )
);

CREATE TABLE phtech_private.reviewer_account_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id TEXT NOT NULL,
    target_id TEXT NOT NULL,
    action TEXT NOT NULL
        CHECK (action IN ('role_changed', 'status_changed')),
    old_value TEXT NOT NULL,
    new_value TEXT NOT NULL,
    changed_at TEXT NOT NULL DEFAULT to_char(
        CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'
    )
);

-- Append-only enforcement on both historical audit streams; do not "fix"
-- mismatched histories by editing or deleting historical records.
CREATE FUNCTION phtech.reject_history_mutation()
RETURNS trigger LANGUAGE plpgsql
AS $trigger$
BEGIN
    RAISE EXCEPTION 'Opportunity review history is append-only';
END;
$trigger$;

CREATE TRIGGER protect_review_updates
    BEFORE UPDATE ON phtech.opportunity_reviews
    FOR EACH ROW EXECUTE FUNCTION phtech.reject_history_mutation();
CREATE TRIGGER protect_review_deletes
    BEFORE DELETE ON phtech.opportunity_reviews
    FOR EACH ROW EXECUTE FUNCTION phtech.reject_history_mutation();

CREATE FUNCTION phtech_private.reject_account_audit_mutation()
RETURNS trigger LANGUAGE plpgsql
AS $trigger$
BEGIN
    RAISE EXCEPTION 'Reviewer account audit history is append-only';
END;
$trigger$;

CREATE TRIGGER protect_account_audit_updates
    BEFORE UPDATE ON phtech_private.reviewer_account_audit
    FOR EACH ROW EXECUTE FUNCTION phtech_private.reject_account_audit_mutation();
CREATE TRIGGER protect_account_audit_deletes
    BEFORE DELETE ON phtech_private.reviewer_account_audit
    FOR EACH ROW EXECUTE FUNCTION phtech_private.reject_account_audit_mutation();

-- No application logins, grants or imported data are created by this script.
COMMIT;
